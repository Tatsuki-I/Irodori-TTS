/* Optional DOM logic check. This is not a browser/audio or listening evaluation. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM,VirtualConsole}=require('jsdom');
const kit=process.argv[2];
if(!kit)throw Error('Usage: node tests/prosody_review_dom.cjs PATH_TO_GENERATED_KIT');
const bundle=JSON.parse(fs.readFileSync(path.join(kit,'bundle.json'),'utf8'));
const html=fs.readFileSync(path.join(kit,'index.html'),'utf8');
const errors=[];let exported;
const consoleProxy=new VirtualConsole();consoleProxy.on('jsdomError',e=>errors.push(String(e)));
const dom=new JSDOM(html,{url:'http://localhost:8765/',runScripts:'dangerously',virtualConsole:consoleProxy,beforeParse(window){
  window.fetch=async name=>{assert.equal(name,'bundle.json');return {ok:true,json:async()=>bundle};};
  window.HTMLCanvasElement.prototype.getContext=()=>new Proxy({}, {get:(target,name)=>target[name]||(()=>{}),set:(target,name,value)=>{target[name]=value;return true;}});
  window.URL.createObjectURL=blob=>{exported=JSON.parse(blob.parts.join(''));return 'blob:test';};
  window.URL.revokeObjectURL=()=>{};
  window.Blob=class {constructor(parts){this.parts=parts;}};
  window.HTMLAnchorElement.prototype.click=function(){};
}});
(async()=>{
 const w=dom.window,$=id=>w.document.getElementById(id),change=id=>$(id).dispatchEvent(new w.Event('change',{bubbles:true}));
 for(let attempt=0;attempt<100&&!$('clip').options.length;attempt++)await new Promise(r=>setTimeout(r,10));
 assert.equal($('clip').options.length,40);
 assert.equal($('perceived_nucleus').options.length,bundle.clips[0].target_moras+2);
 assert.equal($('naturalness').options.length,6);
 assert.equal($('transcript_checked').checked,false);assert.equal($('alignment_checked').checked,false);
 assert.equal($('boundaries').hidden,true);
 assert.ok($('audio').getAttribute('src').startsWith('clips/clip'));
 assert.ok($('baseline').getAttribute('src').startsWith('clips/clip'));
 for(const hidden of ['downstep','caption-n0','arrows-n1'])assert.equal(w.document.body.textContent.includes(hidden),false);
 $('reviewer').value='automated DOM fixture — no listening performed';$('reviewer').dispatchEvent(new w.Event('input'));
 $('notes').value='Test-only draft';change('notes');
 $('perceived_nucleus').value='1';change('perceived_nucleus');
 $('naturalness').value='3';change('naturalness');
 $('show_estimates').checked=true;change('show_estimates');
 assert.equal($('boundaries').hidden,false);
 assert.equal($('moras').rows.length,bundle.clips[0].estimated_moras.length);
 $('export').click();
 assert.equal(exported.fingerprint,bundle.fingerprint);
 assert.equal(exported.reviews[0].transcript_checked,false);
 assert.equal(exported.reviews[0].alignment_checked,false);
 assert.equal(exported.reviews[0].perceived_nucleus,1);
 assert.equal(exported.reviews[0].naturalness,3);
 $('next').click();$('previous').click();assert.equal($('notes').value,'Test-only draft');
 assert.equal($('show_estimates').checked,false);
 const stored=JSON.parse(w.localStorage.getItem('irodori-prosody-review:'+bundle.fingerprint));
 assert.equal(stored.records[bundle.clips[0].code].notes,'Test-only draft');
 w.Storage.prototype.setItem=function(){throw Error('storage unavailable');};
 $('notes').value='Still exportable';change('notes');
 assert.ok($('status').textContent.includes('in memory only'));
 $('export').click();assert.equal(exported.reviews[0].notes,'Still exportable');
 assert.deepEqual(errors,[]);
 console.log('PASS: blind metadata, controls, estimates, draft export and local persistence (DOM only)');
 dom.window.close();
})().catch(error=>{console.error(error);dom.window.close();process.exitCode=1;});
